#!/usr/bin/env python3
"""Write the test language's catalogue, a pseudo-language made longer than English.

    cd sara-godot && python scripts/write_pseudo.py
    python scripts/write_pseudo.py --template translations/sara.pot --out -
    python scripts/write_pseudo.py --check

A German or a Russian sentence runs about 40% longer than the English one, and
a label cut in a lengthened language is cut in those. This writes a catalogue
for the locale `en_XA` in which every message reads as itself made longer: its
letters are swapped for accented Latin and Cyrillic ones, each word gains two
letters in five, the message is topped up at its end until it is two in five
longer as a whole, and the whole sits between `‹` and `›` so a cut end shows. Every
placeholder (`%s`, `%.2f`, `%%`, `{name}`), every BBCode tag and every line
break is kept as it stood, and a message with a plural keeps both its forms.

The catalogue is a test module's, `tests/fixtures/modules/pseudo/language-pseudo`,
which only a run started with `--modules-dir` sees, so no painter is offered it.
`en_XA` is the code Android gives its own accented test language, and Godot
takes it whole and names it "English, XA". The letters chosen are all in the
character map of Inter, the interface's default font.

By default it reads the tree as `write_pot.py` does, so the catalogue holds the
template's messages, the literals that read as a label among them, which
`write_pot_labels.py` finds. `--template` reads a `.pot` file instead, which is
how the suite runs it over a fixture and how `unmarked_texts.py`'s hunt checks that the
template alone marks every text. `--out`
names the file, `-` for standard output. Exits 0 when the catalogue is written.

`--check` builds the catalogue in memory and writes nothing. It exits 1 when
the file on disk differs, naming each message the tree asks for that the file
lacks and each entry no message asks for any more, a context word by its
context, so a catalogue written before a word was given a context is caught.
"""

from __future__ import annotations

import math
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import write_pot
from write_pot_text import po_field
from check_translated import folder_sources, tracked_sources

SARA_GODOT = write_pot.SARA_GODOT
MODULE = SARA_GODOT / "tests" / "fixtures" / "modules" / "pseudo" / "language-pseudo"
LOCALE = "en_XA"
CATALOGUE = MODULE / f"{LOCALE}.po"

# How much longer each word is made, two letters in five.
GROWTH = 0.4

OPEN_MARK = "‹"
CLOSE_MARK = "›"

# What is never changed: a format code, a BBCode tag, a `{name}` of
# String.format, and a line end or a tab, which a reader would see broken.
KEPT = re.compile(
    "|".join(
        (
            write_pot.FORMAT_CODE.pattern,
            write_pot.BBCODE.pattern,
            r"\{[A-Za-z0-9_]*\}",
            r"[\n\t\r]",
        )
    )
)

LETTERS = str.maketrans(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ",
    "áбčďéƒğĥíĵķłмñóþqřšťúvŵхýžÅБÇĐÉФĞĤÎĴЌŁМÑÖÞQŘŠŤÜVŴЖÝŽ",
)

# The letters a word is padded with, Cyrillic, taken in turn.
PADDING = "жщыюёяй"

WORD = re.compile(r"[A-Za-z]+")

HEAD = f"""\
# The test language, generated by scripts/write_pseudo.py from Sara's own
# sentences: every message made about 40% longer in accented Latin and
# Cyrillic letters, so a label a longer language would cut shows cut. Never
# edit it by hand, run the script again.
#
# SPDX-License-Identifier: GPL-3.0-or-later
msgid ""
msgstr ""
"Language: {LOCALE}\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Plural-Forms: nplurals=2; plural=(n != 1);\\n"
"""


@dataclass(frozen=True)
class Message:
    """One message to lengthen: its context, its text and its plural, empty when it has none."""

    context: str
    text: str
    plural: str = ""


def lengthened(text: str) -> str:
    """*text* about 40% longer between its marks, every placeholder and line break as it was."""
    out = []
    at = 0
    for kept in KEPT.finditer(text):
        out.append(_plain(text[at : kept.start()]))
        out.append(kept.group(0))
        at = kept.end()
    out.append(_plain(text[at:]))
    body = "".join(out)
    # Placeholders and spaces do not grow, so a message thick with them is
    # topped up at its end until the whole is two in five longer.
    short = math.ceil(len(text) * (1 + GROWTH)) - len(body) - len(OPEN_MARK) - len(CLOSE_MARK)
    body += "".join(PADDING[i % len(PADDING)] for i in range(max(short, 0)))
    return OPEN_MARK + body + CLOSE_MARK


def _plain(text: str) -> str:
    """A stretch with no placeholder in it, each word swapped and padded."""
    return WORD.sub(_word, text)


def _word(match: re.Match[str]) -> str:
    word = match.group(0)
    extra = math.ceil(len(word) * GROWTH)
    padding = "".join(PADDING[i % len(PADDING)] for i in range(extra))
    if word.isupper() and len(word) > 1:
        padding = padding.upper()
    return word.translate(LETTERS) + padding


def placeholders(text: str) -> list[str]:
    """Every placeholder, tag and line break of *text*, in order, which a translation keeps."""
    return [m.group(0) for m in KEPT.finditer(text)]


def from_tree(root: Path) -> list[Message]:
    """Every message the template holds, its label literals among them, as `write_pot.py` reads the tree."""
    paths = tracked_sources(root) if root == SARA_GODOT else folder_sources(root)
    sources: dict[str, str] = {}
    for path in paths:
        file = root / path
        if file.is_file():
            sources[path] = file.read_text(encoding="utf-8", errors="replace")
    tree = write_pot.Tree(sources, write_pot.kernel_sources(root, root == SARA_GODOT))
    tree.read()
    return [Message(e.context, e.message, e.plural) for e in tree.entries.values()]


def from_template(text: str) -> list[Message]:
    """Every entry of a `.pot`'s text but the header."""
    found = []
    for block in re.split(r"\n\s*\n", text):
        fields: dict[str, str] = {}
        current = ""
        for line in block.splitlines():
            head = re.match(r"^(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?) (\".*\")$", line)
            if head:
                current = head.group(1)
                fields[current] = write_pot.literal(head.group(2))
            elif line.startswith('"') and current:
                fields[current] += write_pot.literal(line)
        if fields.get("msgid"):
            found.append(Message(fields.get("msgctxt", ""), fields["msgid"], fields.get("msgid_plural", "")))
    return found


def catalogue(messages: list[Message]) -> str:
    """The `.po` text of *messages* lengthened, sorted, with no places, so a moved line changes nothing."""
    out = [HEAD]
    for message in sorted(set(messages), key=lambda m: (m.context, m.text, m.plural)):
        out.append("\n")
        if message.context:
            out.append(po_field("msgctxt", message.context))
        out.append(po_field("msgid", message.text))
        if message.plural:
            out.append(po_field("msgid_plural", message.plural))
            out.append(po_field("msgstr[0]", lengthened(message.text)))
            out.append(po_field("msgstr[1]", lengthened(message.plural)))
        else:
            out.append(po_field("msgstr", lengthened(message.text)))
    return "".join(out)


def keys_of(text: str) -> set[tuple[str, str]]:
    """The context and the message of every entry of a catalogue's text."""
    return {(m.context, m.text) for m in from_template(text)}


def check(messages: list[Message], text: str, out: Path) -> int:
    """0 when *out* holds *text*, otherwise 1, naming what differs."""
    on_disk = out.read_text(encoding="utf-8") if out.is_file() else ""
    if on_disk == text:
        print(f"write_pseudo: {out.name} holds the {len(set(messages))} messages the tree asks for")
        return 0
    wanted = keys_of(text)
    held = keys_of(on_disk)
    for context, message in sorted(wanted - held):
        under = f" under the context \"{context}\"" if context else ""
        print(f'write_pseudo: "{message}"{under} has no entry in {out.name}')
    for context, message in sorted(held - wanted):
        under = f" under the context \"{context}\"" if context else ""
        print(f'write_pseudo: "{message}"{under} is in {out.name} and no message asks for it any more')
    if wanted == held:
        print(f"write_pseudo: {out.name} differs from what the tree writes")
    print("write_pseudo: run `python scripts/write_pseudo.py` and commit the catalogue")
    return 1


def main(argv: list[str]) -> int:
    out = CATALOGUE
    if "--out" in argv:
        named = argv[argv.index("--out") + 1]
        out = Path("-") if named == "-" else Path(named).resolve()
    if "--template" in argv:
        template = Path(argv[argv.index("--template") + 1])
        messages = from_template(template.read_text(encoding="utf-8"))
    else:
        messages = from_tree(SARA_GODOT)
    text = catalogue(messages)
    if "--check" in argv:
        return check(messages, text, out)
    if str(out) == "-":
        sys.stdout.write(text)
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"write_pseudo: {len(set(messages))} messages to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
