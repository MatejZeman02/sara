#!/usr/bin/env python3
"""Write American English's catalogue, `en_US.po`, from the tree, and check it.

    cd sara-godot && python scripts/write_en_us.py
    python scripts/write_en_us.py --check

Sara's sentences are British. The module `modules/sara-base-modules/language-en-us` registers a
catalogue that respells them, and this script writes that catalogue so nobody
writes it by hand.

It reads the tree with `write_pot.py`'s reader, imported and not edited, and
takes every message the template holds, the label literals among them, a label joined from literals with `+` read whole. Every literal of the
files the template reads is taken as well, each piece of a joined one too,
since a sentence that starts in lower case or is built at run time is no
label the template holds and can still carry a British word to the screen. Of those it keeps the ones carrying a word of the table,
`modules/sara-base-modules/language-en-us/spellings.json`, and writes each with the word respelt
in the case it had: Colour to Color, COLOUR to COLOR. A word glued to a letter,
a digit or an underscore is part of a name and is left alone, and so is
`%s`. A message with a plural keeps both forms.

`--check` builds the catalogue in memory and exits 1, naming the string and
where it stands, when the file on disk differs: a new string with a British
word and no entry, or an entry no string asks for any more. A second pass names
a word ending in -our, -yse, -iser or -ogue that is on neither the table nor
its keep list, so a British spelling the table never held is caught on the
first string carrying it. A word with a capital inside it is a node's name
and is not read.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import write_pot
from write_pot_text import escaped, po_field
from check_translated import folder_sources, tokens, tracked_sources

SARA_GODOT = write_pot.SARA_GODOT
MODULE = SARA_GODOT / "modules" / "sara-base-modules" / "language-en-us"
CATALOGUE = MODULE / "en_US.po"
TABLE = MODULE / "spellings.json"

WORD = re.compile(r"(?<![A-Za-z0-9_])[A-Za-z]+(?![A-Za-z0-9_])")
UNSETTLED = re.compile(r"(?:our|yse|iser|ogue)s?$", re.I)

HEAD = """\
# American English, generated by scripts/write_en_us.py from Sara's own
# sentences. Never edit it by hand: change the table beside it,
# spellings.json, and run the script again.
#
# SPDX-License-Identifier: GPL-3.0-or-later
msgid ""
msgstr ""
"Language: en_US\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Plural-Forms: nplurals=2; plural=(n != 1);\\n"
"""


class Table:
    """The British words and their American spellings, and the words kept as they are."""

    def __init__(self, path: Path):
        data = json.loads(path.read_text(encoding="utf-8"))
        self.respell: dict[str, str] = {k.lower(): v.lower() for k, v in data["respell"].items()}
        self.keep: dict[str, str] = {k.lower(): v for k, v in data.get("keep", {}).items()}

    def american(self, text: str) -> str:
        """*text* with every word of the table respelt in the case it had."""
        return WORD.sub(lambda m: self._word(m.group(0)), text)

    def _word(self, word: str) -> str:
        wanted = self.respell.get(word.lower())
        if wanted is None:
            return word
        if word.isupper() and len(word) > 1:
            return wanted.upper()
        if word[0].isupper():
            return wanted[0].upper() + wanted[1:]
        return wanted

    def unknown(self, text: str) -> list[str]:
        """The words of *text* that look British and that neither list holds."""
        out = []
        for word in WORD.findall(text):
            if any(c.isupper() for c in word[1:]) and not word.isupper():
                continue
            lower = word.lower()
            if UNSETTLED.search(lower) and lower not in self.respell and lower not in self.keep:
                out.append(word)
        return out


class Message:
    """One entry of the catalogue: its source text, its plural, and where it first stands."""

    def __init__(self, context: str, text: str, plural: str, where: str):
        self.context = context
        self.text = text
        self.plural = plural
        self.where = where

    def key(self) -> tuple[str, str]:
        return (self.context, self.text)


def messages(root: Path) -> list[Message]:
    """Every message of the template and every literal of the same files, each once."""
    paths = tracked_sources(root) if root == SARA_GODOT else folder_sources(root)
    sources: dict[str, str] = {}
    for path in paths:
        file = root / path
        if file.is_file():
            sources[path] = file.read_text(encoding="utf-8", errors="replace")
    tree = write_pot.Tree(sources, write_pot.kernel_sources(root, root == SARA_GODOT))
    tree.read()
    found: dict[tuple[str, str], Message] = {}
    for entry in tree.entries.values():
        path, line = entry.first()
        message = Message(entry.context, entry.message, entry.plural, f"{path}:{line}")
        found[message.key()] = message
    held = {m.plural for m in found.values() if m.plural}
    for path in sorted(sources):
        for token in tokens(sources[path]):
            if token.kind != "str":
                continue
            text = write_pot.literal(token.text)
            if write_pot.has_letter(text) and ("", text) not in found and text not in held:
                found[("", text)] = Message("", text, "", f"{path}:{token.line}")
    return list(found.values())


def build(root: Path, table: Table) -> tuple[list[tuple[Message, str, str]], list[str]]:
    """The entries the catalogue holds, sorted, and the words the second pass names."""
    entries = []
    unknown = []
    for message in messages(root):
        for text in (message.text, message.plural):
            unknown.extend(f"{message.where}: '{w}' in \"{text}\"" for w in table.unknown(text))
        singular = table.american(message.text)
        plural = table.american(message.plural) if message.plural else ""
        if singular != message.text or plural != message.plural:
            entries.append((message, singular, plural))
    entries.sort(key=lambda e: (e[0].context, e[0].text))
    return entries, sorted(set(unknown))


def catalogue(entries: list[tuple[Message, str, str]]) -> str:
    """The `.po` text of *entries*, with no places, so a moved line changes nothing."""
    out = [HEAD]
    for message, singular, plural in entries:
        out.append("\n")
        if message.context:
            out.append(po_field("msgctxt", message.context))
        out.append(po_field("msgid", message.text))
        if message.plural:
            out.append(po_field("msgid_plural", message.plural))
            out.append(po_field("msgstr[0]", singular))
            out.append(po_field("msgstr[1]", plural))
        else:
            out.append(po_field("msgstr", singular))
    return "".join(out)


def ids_of(text: str) -> set[str]:
    """The msgids a catalogue's text holds, the header's empty one left out."""
    found = set()
    for block in re.findall(r'^msgid ((?:".*"\n)+)', text, re.M):
        joined = "".join(re.findall(r'^"(.*)"$', block, re.M))
        if joined:
            found.add(joined)
    return found


def main(argv: list[str]) -> int:
    root = SARA_GODOT
    out = CATALOGUE
    table_path = TABLE
    if "--root" in argv:
        root = Path(argv[argv.index("--root") + 1]).resolve()
    if "--out" in argv:
        out = Path(argv[argv.index("--out") + 1]).resolve()
    if "--table" in argv:
        table_path = Path(argv[argv.index("--table") + 1]).resolve()
    table = Table(table_path)
    entries, unknown = build(root, table)
    text = catalogue(entries)
    if "--check" not in argv:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"write_en_us: {len(entries)} messages to {out}")
        for line in unknown:
            print(f"write_en_us: neither respelt nor kept, {line}")
        return 1 if unknown else 0
    on_disk = out.read_text(encoding="utf-8") if out.is_file() else ""
    failed = False
    if on_disk != text:
        failed = True
        wanted = {escaped(m.text): m for m, _s, _p in entries}
        held = ids_of(on_disk)
        for spelt in sorted(set(wanted) - held):
            print(f"write_en_us: {wanted[spelt].where}: \"{wanted[spelt].text}\" has no American entry")
        for spelt in sorted(held - set(wanted)):
            print(f'write_en_us: "{spelt}" is in {out.name} and no string asks for it any more')
        if set(wanted) == held:
            print(f"write_en_us: {out.name} differs from what the tree writes")
        print("write_en_us: run `python scripts/write_en_us.py` and commit the catalogue")
    for line in unknown:
        failed = True
        print(f"write_en_us: neither respelt nor kept, {line}, add it to {table_path.name}")
    if not failed:
        print(f"write_en_us: {out.name} holds the {len(entries)} messages the tree asks for")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
