"""The step kinds page `sara_steps.py --page` writes, the lines, and its `--check`.

    cd sara-godot && PYTHONPATH=scripts python3 -m unittest scripts.test_sara_steps

The page is generated so it cannot drift from the table, which
holds only while the check fails on a table that moved. So the check is run
against a scratch copy of `harness/sa_step_table.gd` with one step added, and
the committed page is read against the real one.

Needs no Godot, no GPU and no weston.
"""

from __future__ import annotations

import io
import tempfile
import unittest
import unittest.mock
from contextlib import redirect_stdout
from pathlib import Path, PureWindowsPath

import sara_steps as steps

ZOOM_BRANCH = '    elif step.has("zoom"):\n'
NEW_BRANCH = '    elif step.has("w3_scratch_step"):\n        _canvas.zoom(float(step["w3_scratch_step"]))\n'


class PageTests(unittest.TestCase):
    def setUp(self) -> None:
        self.scratch = Path(tempfile.mkdtemp())

    def _run(self, check: bool, page: Path) -> int:
        with redirect_stdout(io.StringIO()):
            return steps.write_page(check, page)

    @unittest.skipUnless(steps.PAGE.exists(), "a copy without docs/ has no committed page to read")
    def test_the_committed_page_is_what_the_table_writes(self) -> None:
        self.assertEqual(self._run(True, steps.PAGE), 0, "run `python scripts/sara_steps.py --page`")

    def test_the_page_names_every_step_once_with_a_sentence(self) -> None:
        text = steps.page_text()
        # The last branch of a key is its line, as `import` has two.
        for entry in {entry["step"]: entry for entry in steps.catalogue()}.values():
            lines = [line for line in text.splitlines() if line.startswith("- `%s`," % entry["step"])]
            self.assertEqual(len(lines), 1, entry["step"])
            self.assertIn(steps.first_sentence(entry["doc"]), lines[0])
        self.assertTrue(text.splitlines()[2].startswith("Generated by `sara-godot/scripts/sara_steps.py --page`"))

    def test_the_writer_writes_and_then_the_check_passes(self) -> None:
        page = self.scratch / "DOOR-STEPS.md"
        self.assertEqual(self._run(True, page), 1)
        self.assertFalse(page.exists(), "--check writes nothing")
        self.assertEqual(self._run(False, page), 0)
        self.assertEqual(page.read_text(encoding="utf-8"), steps.page_text())
        self.assertEqual(self._run(True, page), 0)

    def _main(self, *argv: str) -> int:
        with unittest.mock.patch("sys.argv", ["sara_steps.py", *argv]), redirect_stdout(io.StringIO()):
            return steps.main()

    def test_the_page_goes_where_out_names_and_the_check_reads_the_same_file(self) -> None:
        """A copy with no docs/ has no default folder, so `--out` is how it writes the page."""
        page = self.scratch / "elsewhere.md"
        self.assertEqual(self._main("--page", "--check", "--out", str(page)), 1)
        self.assertEqual(self._main("--page", "--out", str(page)), 0)
        self.assertEqual(page.read_text(encoding="utf-8"), steps.page_text())
        self.assertEqual(self._main("--page", "--check", "--out", str(page)), 0)

    def test_a_page_with_no_folder_to_land_in_is_refused_with_the_way_out(self) -> None:
        missing = self.scratch / "no-such-folder" / "DOOR-STEPS.md"
        self.assertEqual(self._main("--page", "--out", str(missing)), 2)
        self.assertFalse(missing.parent.exists())

    def test_out_without_page_is_an_error(self) -> None:
        with self.assertRaises(SystemExit):
            with unittest.mock.patch("sys.stderr", io.StringIO()):
                self._main("--out", str(self.scratch / "x.md"))

    def test_a_step_added_without_regenerating_fails_the_check(self) -> None:
        page = self.scratch / "DOOR-STEPS.md"
        self._run(False, page)
        table = self.scratch / "sa_step_table.gd"
        source = steps.EXECUTOR.read_text(encoding="utf-8")
        self.assertIn(ZOOM_BRANCH, source)
        table.write_text(source.replace(ZOOM_BRANCH, NEW_BRANCH + ZOOM_BRANCH, 1), encoding="utf-8")
        with unittest.mock.patch.object(steps, "EXECUTOR", table):
            self.assertIn("w3_scratch_step", steps.page_text())
            self.assertEqual(self._run(True, page), 1)

    def test_a_branch_wrapped_in_a_printer_documents_the_call_inside_it(self) -> None:
        """A kind whose dispatch is wrapped in `print` or in `SaDoorVerdicts.say`.

        Two kinds hand their line to the door's verdicts rather than printing
        it, and read as one kind with the printer's doc until the printer was
        unwrapped, which left `layers` and `glance` sharing a line.
        """
        last = {entry["step"]: entry for entry in steps.catalogue()}
        self.assertEqual(last["measure"]["handler"], "SaMeasure.capture", "print(...) unwraps")
        self.assertEqual(last["glance"]["handler"], "DoorGlance.capture", "say(...) unwraps")
        self.assertEqual(last["layers"]["handler"], "_report.layers_line")
        wrapped = [entry["step"] for entry in steps.catalogue() if entry["handler"].startswith(steps.PRINTERS)]
        self.assertEqual(wrapped, [], "no kind is documented by the call that only writes its line out")

    def test_the_first_sentence_stops_at_a_full_stop(self) -> None:
        self.assertEqual(steps.first_sentence("Paints a line.\nThen waits. For long."), "Paints a line.")
        self.assertEqual(steps.first_sentence("Reads `a.b` in full.\n\nA second paragraph."), "Reads `a.b` in full.")
        self.assertEqual(steps.first_sentence(""), "")

    def test_the_page_opens_with_the_start_kinds(self) -> None:
        head = steps.page_text().split("\n## ", 1)[0]
        self.assertIn("**Start here.**", head)
        for key in steps.START:
            self.assertIn("`%s`" % key, head, key)
        self.assertIn("array of answers", head)

    def test_a_res_path_built_on_windows_reads_with_forward_slashes(self) -> None:
        project = PureWindowsPath("C:\\Users\\painter\\sara\\sara-godot")
        path = project / "harness" / "drivers" / "sa_input_driver.gd"
        self.assertEqual(steps.res_path_of(path, project), "res://harness/drivers/sa_input_driver.gd")

    def test_every_class_file_reads_with_forward_slashes(self) -> None:
        for name, path in steps.class_files().items():
            self.assertNotIn("\\", path, name)
            self.assertTrue(path.startswith("res://"), name)


def _entry(key: str, doc: str) -> dict:
    """A catalogue entry of *key* whose handler's doc is *doc*."""
    return {"step": key, "doc": doc, "argument": "any", "line": 1, "documented": True, "handler": "", "file": ""}


class LineTests(unittest.TestCase):
    """The line a kind is listed by, and the check that holds it.

    The door answers `{"steps": true}` with each kind's line rather than its
    first sentence, which is what brought the answer from 43,030 characters to
    under ten thousand, so the cut and the check are the budget's guard.
    """

    def test_the_line_is_the_first_sentence_up_to_a_colon_or_a_backtick(self) -> None:
        self.assertEqual(steps.line_of('Zooms the main canvas: to `value`, keeping the centre.'), "Zooms the main canvas")
        self.assertEqual(steps.line_of('Opens a dropdown by name, `{"dropdown": "X"}`.'), "Opens a dropdown by name")
        self.assertEqual(steps.line_of("Paints one stroke. The only step that changes the canvas."), "Paints one stroke")
        self.assertEqual(steps.line_of("Saves the main document.\n\nA second paragraph: here."), "Saves the main document")
        self.assertEqual(steps.line_of(""), "")

    def _check(self, entries: list[dict]) -> int:
        with (
            unittest.mock.patch.object(steps, "catalogue", lambda: entries),
            unittest.mock.patch.object(steps, "START", ()),
            unittest.mock.patch("sys.argv", ["sara_steps.py", "--check"]),
            redirect_stdout(io.StringIO()) as printed,
        ):
            code = steps.main()
        self.printed = printed.getvalue()
        return code

    def test_check_fails_a_line_of_41_characters_and_passes_one_of_40(self) -> None:
        forty = "Paints a line across the whole wide page"
        self.assertEqual(len(forty), 40)
        self.assertEqual(self._check([_entry("w", forty + ": `{}`.")]), 0, self.printed)
        self.assertEqual(self._check([_entry("w", forty + "s: `{}`.")]), 1)
        self.assertIn("41 characters", self.printed)
        self.assertIn("`w`", self.printed)

    def test_a_line_that_is_not_a_clause_is_named(self) -> None:
        for doc, why in [
            ("Zooms the main canvas to `value`.", "ends on 'to'"),
            ("The `tool` step: picks a tool.", "is one word"),
            ("The gradient's drag, in document pixels.", "not a verb"),
            ("drags a row: of the docker.", "capital letter"),
            ("Reads the rows (of the page: all.", "leaves a ( open"),
        ]:
            self.assertEqual(self._check([_entry("w", doc)]), 1, doc)
            self.assertIn(why, self.printed, doc)

    def test_two_kinds_of_one_line_are_named(self) -> None:
        self.assertEqual(self._check([_entry("press", "Presses: a."), _entry("release", "Presses: b.")]), 1)
        self.assertIn("`press` and `release` share one line", self.printed)

    def test_a_start_kind_needs_an_arguments_paragraph(self) -> None:
        bare = [_entry("stroke", "Paints one stroke.")]
        self.assertIn("start kind `stroke` has no", "\n".join(steps.line_problems(bare, ("stroke",))))
        self.assertIn("start kind `look` is not in the table", "\n".join(steps.line_problems(bare, ("look",))))
        self.assertEqual(steps.line_problems(bare, ("quit",)), [], "the door answers quit itself")

    def test_every_kind_of_the_table_passes(self) -> None:
        self.assertEqual(steps.line_problems(steps.catalogue()), [])


class ArgumentTests(unittest.TestCase):
    """The `Arguments` paragraph a start kind's doc carries, read into its schema."""

    DOC = (
        "Paints one stroke.\n\n**Arguments.**\n- `from` array, `[x, y]` where it starts.\n"
        "- `pressure` number or array, 0 to 1,\nor a ramp.\n- `bad` a line that names no type.\n\nMore."
    )

    def test_each_line_is_a_key_with_its_types_and_words(self) -> None:
        self.assertEqual(
            steps.arguments_of(self.DOC),
            {"from": (["array"], "`[x, y]` where it starts"), "pressure": (["number", "array"], "0 to 1, or a ramp")},
        )
        self.assertEqual(steps.arguments_of("Paints one stroke.\n\nNo paragraph."), {})

    def test_the_schema_types_the_keys_of_the_argument(self) -> None:
        schema = steps.input_schema("stroke", "Dictionary", steps.arguments_of(self.DOC))
        self.assertEqual(schema["required"], ["stroke"])
        value = schema["properties"]["stroke"]
        self.assertEqual(value["type"], "object", "the value's own type stays the cast's")
        self.assertEqual(value["properties"]["from"], {"type": "array", "description": "`[x, y]` where it starts"})
        self.assertEqual(value["properties"]["pressure"]["type"], ["number", "array"])

    def test_a_line_naming_the_kind_describes_its_value(self) -> None:
        typed = steps.input_schema("undo", "int", {"undo": (["integer"], "how many steps back")})
        self.assertEqual(typed["properties"]["undo"], {"type": "integer", "description": "how many steps back"})
        untyped = steps.input_schema("colour", "any", {"colour": (["string", "array"], "a hex code")})
        self.assertEqual(untyped["properties"]["colour"], {"description": "string or array, a hex code"})

    def test_every_start_kind_of_the_table_is_flagged_with_a_schema_that_says_more_than_a_type(self) -> None:
        last = {entry["step"]: entry for entry in steps.catalogue()}
        for key in steps.START:
            if key in steps.DOOR_ONLY:
                continue
            self.assertTrue(last[key]["start"], key)
            value = last[key]["inputSchema"]["properties"][key]
            self.assertTrue(value.get("properties") or value.get("description"), key)
        self.assertFalse(last["zoom"]["start"])
        self.assertEqual(
            last["zoom"]["inputSchema"],
            {"type": "object", "properties": {"zoom": {"type": "number"}}, "required": ["zoom"]},
            "a kind with no paragraph keeps the schema it had",
        )


if __name__ == "__main__":
    unittest.main()
